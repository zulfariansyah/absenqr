def get_translation(key: str, lang: str = 'id', **kwargs) -> str:
    """Mengambil teks terjemahan berdasarkan key dan bahasa yang dipilih"""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS['id'])
    text = lang_dict.get(key)
    if text is None:
        # Fallback ke bahasa Indonesia jika key tidak ditemukan di bahasa target
        text = TRANSLATIONS['id'].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def get_all_translations_json(lang: str = 'id') -> dict:
    """Mengembalikan dictionary terjemahan untuk di-render ke frontend JavaScript"""
    target = TRANSLATIONS.get(lang, TRANSLATIONS['id'])
    # Gabungkan dengan fallback ID
    merged = dict(TRANSLATIONS['id'])
    merged.update(target)
    return merged
